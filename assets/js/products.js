// Helper calculations
function getDiscountPercentage(product) {
  if (!product.mrp || !product.price) return 0;
  return Math.round(((product.mrp - product.price) / product.mrp) * 100);
}

function getSavingsAmount(product) {
  if (!product.mrp || !product.price) return 0;
  return product.mrp - product.price;
}

